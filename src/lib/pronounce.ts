function tidy(raw: string) {
  let text = raw
    .replace(/O\(n\s*\*\s*n\)|O\(n²\)|O\(n\^2\)/gi, "order n squared")
    .replace(/O\(n log n\)/gi, "order n log n")
    .replace(/O\(log n\)/gi, "order log n")
    .replace(/O\(1\)/gi, "constant time")
    .replace(/O\(n\)/gi, "linear time")
    .replace(/unordered_map/gi, "unordered map")
    .replace(/push_back/gi, "push back")
    .replace(/nums\[i\]/gi, "nums of i")
    .replace(/seen\[([^\]]+)\]/gi, "seen of $1")
    .replace(/\bcount\s*\(/gi, "count ")
    .replace(/::/g, " ")
    .replace(/→|=>/g, " ")
    .replace(/[\[\]{}()=*<>]/g, " ")
    .replace(/[`*_#]/g, " ")
    .replace(/\.\.\./g, ". ")
    .replace(/,/g, ", ")
    .replace(/\s+/g, " ")
    .trim();
  text = text.replace(/([.!?])\s*/g, "$1 ");
  if (text && !/[.!?।]$/.test(text)) text += ".";
  return text.replace(/\s+/g, " ").trim();
}

function tokenToSpeak(token: string) {
  const m = token.match(/^([^A-Za-z]*)([A-Za-z']+)([^A-Za-z]*)$/);
  if (!m) return token;
  const [, pre, word, post] = m;
  const key = word.toLowerCase();
  if (TECH.has(key)) return `${pre}${word}${post}`;
  if (Object.prototype.hasOwnProperty.call(HI, key)) {
    const hi = HI[key];
    if (!hi) return pre + post;
    return `${pre}${hi}${post}`;
  }
  return `${pre}${word}${post}`;
}

export function hinglishSpeak(raw: string) {
  return tidy(raw)
    .split(/(\s+)/)
    .map((part) => (/^\s+$/.test(part) ? part : tokenToSpeak(part)))
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}

export function naturalHinglish(raw: string) {
  // Keep roman Hinglish. Indian English neural voices sound far more natural
  // on this than forced Devanagari word swaps.
  return flowSpeech(
    tidy(raw)
      .replace(/\bchahiye\b/gi, "chaahiye")
      .replace(/\bkyunki\b/gi, "kyoon ki")
      .replace(/\bkya\b/gi, "kyaa")
      .replace(/\bnahi\b/gi, "nahee")
      .replace(/\bdhyan\b/gi, "dhyaan")
      .replace(/\bpehle\b/gi, "pehley")
  );
}

/** Turn choppy sentence stops into lighter commas so TTS does not stall. */
function flowSpeech(raw: string) {
  const parts = raw
    .replace(/।/g, ".")
    .split(/(?<=[.!?])\s+/)
    .map((p) => p.trim())
    .filter(Boolean);
  if (parts.length <= 1) return raw.trim();
  const body = parts
    .map((p, idx) => {
      const core = p.replace(/[.!?]+$/g, "").trim();
      if (!core) return "";
      // Keep a real stop only on the last clause
      if (idx === parts.length - 1) return `${core}.`;
      return `${core},`;
    })
    .filter(Boolean)
    .join(" ");
  return body.replace(/\s+/g, " ").trim();
}

export function prepareSpeech(raw: string, lang: string) {
  const text = tidy(raw);
  if (lang === "english") {
    return { text: flowSpeech(text), voice: "en-IN-NeerjaNeural", rate: "+8%" };
  }
  if (lang === "hindi") {
    const spoken = /[\u0900-\u097F]/.test(text) ? text : hinglishSpeak(text);
    return { text: flowSpeech(spoken), voice: "hi-IN-SwaraNeural", rate: "+5%" };
  }
  // Hinglish = Indian male teacher reading natural roman Hinglish
  return { text: naturalHinglish(text), voice: "en-IN-PrabhatNeural", rate: "+10%" };
}

export function ratePercent(speed: number) {
  // Base voice is already slightly fast; speed multiplies from there.
  if (speed >= 2) return "+35%";
  if (speed >= 1.8) return "+28%";
  if (speed >= 1.5) return "+20%";
  if (speed >= 1.25) return "+14%";
  if (speed >= 1) return "+10%";
  return "+2%";
}

export function escapeXml(text: string) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/** Keep SSML simple — Edge neural voices time out on heavy break markup. */
export function toSsml(text: string, voice: string, rate: string) {
  const lang = voice.startsWith("hi-") ? "hi-IN" : "en-IN";
  const safe = escapeXml(text);
  return (
    `<speak version="1.0" xmlns="http://www.w3.org/2001/10/synthesis" xml:lang="${lang}">` +
    `<voice name="${voice}"><prosody rate="${rate}">${safe}</prosody></voice>` +
    `</speak>`
  );
}
